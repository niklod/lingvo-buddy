"""Exports the ranked lemma list from wordfreq (needs the packages in requirements-export.txt)."""

from __future__ import annotations

import argparse
import sys
from importlib.metadata import version
from pathlib import Path
from typing import Dict, FrozenSet, List, Mapping, Optional, Sequence

from lingvo_dict.paths import WORDLIST_DIR
from lingvo_dict.text_lines import content_lines
from lingvo_dict.wordlist import (
    ExportRules,
    Lemmatize,
    WordListResult,
    format_exclusion_report,
    format_word_list,
    rank_lemmas,
)

LANGUAGE = "en"
WORDFREQ_LIST = "best"
# Far more forms than lemmas are needed: inflections fold into one lemma and
# the exclusions drop many tokens before rank 10000 is reached.
SOURCE_FORMS = 60000
LIMIT = 10000
LEMMA_POS_ORDER = ("VERB", "NOUN", "ADJ", "ADV", "AUX")


def read_lines(path: Path) -> List[str]:
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError as error:
        raise ValueError(f"{path}: not UTF-8 text: {error}") from error
    return [line for _, line in content_lines(text)]


def read_set(path: Path, lowercase: bool) -> FrozenSet[str]:
    return frozenset(line.lower() if lowercase else line for line in read_lines(path))


def read_overrides(path: Path) -> Dict[str, str]:
    overrides: Dict[str, str] = {}
    for line in read_lines(path):
        parts = [part.strip() for part in line.split("\t")]
        if len(parts) != 2 or not all(parts):
            raise ValueError(f"{path}: expected 'form<TAB>lemma', got {line!r}")
        form, lemma = parts
        if form in overrides:
            raise ValueError(f"{path}: form {form!r} is listed twice")
        overrides[form] = lemma
    return overrides


def load_rules(folder: Path) -> ExportRules:
    return ExportRules(
        exclusions=read_set(folder / "exclusions.txt", lowercase=True),
        keep=read_set(folder / "keep.txt", lowercase=False),
        lemma_overrides=read_overrides(folder / "lemma-overrides.tsv"),
    )


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=WORDLIST_DIR, help="word list folder")
    args = parser.parse_args(argv)

    try:
        rules = load_rules(args.data)
    except (OSError, UnicodeDecodeError, ValueError) as error:
        print(f"error: cannot read the export rules: {error}", file=sys.stderr)
        return 2
    try:
        # Optional packages: only this export needs them, the validator and the build run without.
        import wordfreq

        lemmatize = make_lemmatizer()
    except ImportError as error:
        print(f"error: {error}. Install tools/dictionary/requirements-export.txt.", file=sys.stderr)
        return 2

    forms = [
        (form, wordfreq.word_frequency(form, LANGUAGE, wordlist=WORDFREQ_LIST))
        for form in wordfreq.top_n_list(LANGUAGE, SOURCE_FORMS, wordlist=WORDFREQ_LIST)
    ]
    result = rank_lemmas(forms, lemmatize, rules, LIMIT)
    if len(result.words) != LIMIT:
        print(f"error: only {len(result.words)} lemmas, expected {LIMIT}", file=sys.stderr)
        return 1
    try:
        _write_files(args.data, result)
    except OSError as error:
        print(f"error: cannot write to {args.data}: {error}", file=sys.stderr)
        return 1
    print(f"wrote {len(result.words)} lemmas, {len(result.excluded)} exclusions to {args.data}")
    return 0


def _write_files(folder: Path, result: WordListResult) -> None:
    header = [
        f"source: wordfreq {version('wordfreq')} ({LANGUAGE}, wordlist={WORDFREQ_LIST}, top {SOURCE_FORMS} forms)",
        f"lemmatizer: simplemma {version('simplemma')}, lemminflect {version('lemminflect')}",
        "license: wordfreq data by Robyn Speer, CC BY-SA 4.0, https://github.com/rspeer/wordfreq",
        "generated by tools/dictionary/export_wordlist.py; do not edit by hand",
    ]
    (folder / "wordlist.tsv").write_text(format_word_list(result.words, header), encoding="utf-8")
    report_header = header[:2] + ["lemmas removed by a rule or exclusions.txt that are frequent enough to rank"]
    (folder / "excluded.tsv").write_text(format_exclusion_report(result.excluded, report_header), encoding="utf-8")


def make_lemmatizer() -> Lemmatize:
    """simplemma first; lemminflect repairs lemmas that are not words.

    simplemma cuts some -ing/-ed forms badly ("playing" -> "playe", "gone" -> "gan").
    When lemminflect does not know simplemma's lemma as a lemma but knows the
    form, its lemma (verb first) replaces it.
    """
    import simplemma
    from lemminflect import getAllLemmas

    def lemmatize(form: str) -> Optional[str]:
        if not simplemma.is_known(form, lang=LANGUAGE):
            return None
        lemma: str = simplemma.lemmatize(form, lang=LANGUAGE)
        if lemma != lemma.lower() or _is_lemma(lemma, getAllLemmas(lemma)):
            return lemma
        repaired = _first_lemma(getAllLemmas(form))
        return repaired or lemma

    return lemmatize


def _is_lemma(word: str, lemmas: Mapping[str, Sequence[str]]) -> bool:
    return any(word in candidates for candidates in lemmas.values())


def _first_lemma(lemmas: Mapping[str, Sequence[str]]) -> Optional[str]:
    return next((lemmas[pos][0] for pos in LEMMA_POS_ORDER if pos in lemmas), None)
